// Wires the question bank into the app and service worker.
//
// The app has exactly one bank: the single file under `public/banks/`.
// Running the build regenerates everything that references it:
//
//   - the file's "id" field must match its filename, and it must have
//     "title", "subtitle", and a "questions" array (violations fail the
//     build here, not silently in a browser),
//   - `src/Banks.elm` is regenerated (the bank id the app fetches),
//   - the bank file list in `public/sw.js` between the BANKS markers
//     is regenerated so offline precaching covers the bank.
//
// Runs automatically via the `prebuild` and `pretest` npm scripts.

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const banksDir = path.join(root, "public", "banks");

const ids = fs
  .readdirSync(banksDir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => path.basename(f, ".json"))
  .sort();

if (ids.length === 0) {
  throw new Error("scripts/gen-banks: no bank file in public/banks/");
}

if (ids.length > 1) {
  throw new Error(`scripts/gen-banks: expected one bank file, found [${ids.join(", ")}]`);
}

const id = ids[0];

const file = path.join(banksDir, id + ".json");
const bank = JSON.parse(fs.readFileSync(file, "utf8"));
if (bank.id !== id) {
  throw new Error(`scripts/gen-banks: ${file} has id "${bank.id}", expected "${id}"`);
}
for (const field of ["title", "subtitle", "questions"]) {
  if (bank[field] === undefined) {
    throw new Error(`scripts/gen-banks: ${file} is missing "${field}"`);
  }
}
if (!Array.isArray(bank.questions) || bank.questions.length === 0) {
  throw new Error(`scripts/gen-banks: ${file} has no questions`);
}

const elm =
  `module Banks exposing (default)

{-| Generated by scripts/gen-banks.js — do not edit. The id of the bank file
found under public/banks/ at build time.
-}


default : String
default =
    "${id}"
`;
fs.writeFileSync(path.join(root, "src", "Banks.elm"), elm);

const swPath = path.join(root, "public", "sw.js");
const sw = fs.readFileSync(swPath, "utf8");
const start = "// BANKS-START";
const end = "// BANKS-END";
const before = sw.slice(0, sw.indexOf(start) + start.length);
const after = sw.slice(sw.indexOf(end));
fs.writeFileSync(swPath, `${before}\n  'banks/${id}.json',\n${after}`);

console.log(`scripts/gen-banks: bank "${id}" (${bank.questions.length} questions)`);
